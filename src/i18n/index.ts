export type Locale = 'en' | 'id';
const saved = (() => {
  try {
    return localStorage.getItem('workstel.locale');
  } catch {
    return null;
  }
})();
export const locale = ref<Locale>(saved === 'id' ? 'id' : 'en');
export function t(key: MessageKey): string {
  return locale.value === 'id' ? indonesian[key] : english[key];
}
const keys = Object.keys(english) as MessageKey[];
export function translate(value: string): string {
  const key = keys.find((k) => english[k] === value);
  return key ? t(key) : value;
}
watch(
  locale,
  (value) => {
    document.documentElement.lang = value;
    try {
      localStorage.setItem('workstel.locale', value);
    } catch {
      /* Keep the language for the current session when storage is unavailable. */
    }
  },
  { immediate: true },
);
